const TEXTS: Record<Lang, Texts> = { es, en };

export function textsFor(lang: Lang): Texts {
  return TEXTS[lang];
}

export type { Texts };

/** Etiqueta de un id del motor, o el id tal cual si el módulo no lo conoce:
 *  un id nuevo del catálogo se ve crudo antes que desaparecer. */
export function labelOf(table: Record<string, string>, id: string): string {
  return table[id] ?? id;
}

/** Cuántas veces se lanza gratis un conjuro de rasgo. Dos fuentes del mismo
 *  conjuro llegan del motor como una fila con los usos sumados, y ahí el
 *  rótulo fijo de «1/descanso» mentiría. */
export function innateUseLabel(t: Texts, s: { use: string; freeUses: number }): string {
  const perRest = t.innateTimesPerRest;
  return s.freeUses > 1 && s.use in perRest
    ? perRest[s.use as keyof typeof perRest](s.freeUses)
    : labelOf(t.innateUses, s.use);
}

const STORAGE_KEY = 'milantus.locale';

/** Recuerda el idioma elegido, con la misma clave que Flutter: el cambio vale
 *  en los dos clientes. Devuelve si pudo guardarlo: el idioma se resuelve
 *  una sola vez al cargar, así que sin almacenamiento (modo privado) recargar
 *  no lo cambiaría y la pantalla no recarga. */
export function storeLang(lang: Lang): boolean {
  try {
    window.localStorage.setItem(STORAGE_KEY, lang);
    return window.localStorage.getItem(STORAGE_KEY) === lang;
  } catch {
    return false;
  }
}

/** El idioma de la interfaz, resuelto como `resolveLocale` de Flutter
 *  (`l10n/app_locale.dart`): el guardado si es válido; si no, el del
 *  navegador si lo soportamos (`en-US` vale `en`); si no, español. Flutter lo
 *  guarda en `localStorage`, y `/v2` comparte origen, así que es el mismo. */
export function resolveLang(): Lang {
  const base = (tag: string | null | undefined): Lang | null => {
    const code = tag?.toLowerCase().split(/[-_]/)[0];
    return code === 'es' || code === 'en' ? code : null;
  };
  let stored: string | null = null;
  try {
    stored = window.localStorage.getItem(STORAGE_KEY);
  } catch {
    // El almacenamiento bloqueado equivale a «no hay idioma guardado».
  }
  return base(stored) ?? base(navigator.language) ?? 'es';
}
